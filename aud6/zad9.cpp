// Да се напише програма која од тастатура чита непознат број на тројки цели позитивни (int) броеви: A, B и контролен број K (се читаат додека не се внесе нешто што не е број). Доколку броевите имаат различен број на цифри, потребно е да се претпостави дека помалкуцифрените броеви имаат цифри 0 пред најзначајната цифра (најлево).
//
// На основа на овие три броja треба да се формира комбиниран број. Комбинираниот број се конструира со помош на цифрите на A и B во однос на контролниот број К oдејќи оддесно - нaлево, според следните правила:
//
// Ако разликата помеѓу соодветните цифри
//
// ∣Acifra−Bcifra|
//
//
// 1) .. е помала од соодветната цифра на контролниот број K, се внесува цифрата од A.
//
// 2) .. е поголема од соодветната цифра на контролниот број K, се внесува цифрата од B.
//
// 3) .. е еднаква на соодветната цифра на контролниот број K, тогаш не се внесува ништо (цифрата се прескокнува).
//
// На крај, комбинираниот број се печати за секоја внесена тројка (редоследот на цифрите е како во примерот).
//
// Трансформирањето на броeвите да се реши со функција/функции за освојување максимален број поени.
//
// Објаснување:
//
//                        ← (се чита оддесно - нaлево)
// А = 4315       0 4 3 1 5
// В = 678        0 0 6 7 8
// К = 23356      2 3 3 5 6
//
//
// |5 - 8| = 3, 3 < 6, во комбинираниот број се внесува цифрата од A: 5
// |1 - 7| = 6, 6 > 5, во комбинираниот број се внесува цифрата од B: 7
// |3 - 6| = 3, 3 = 3, СЕ ИГНОРИРА, не се внесува цифра
// |4 - 0| = 4, 4 > 3, во комбинираниот број се внесува цифрата од B: 0
// |0 - 0| = 0, 0 < 2, во комбинираниот број се внесува цифрата од A: 0
// Kомбинираниот број е: 75

int transform(int a, int b, int k) {
    int komb = 0;
    int stepen = 1;
    while (a > 0 || b > 0 || k > 0) {
        int aCifra = a % 10;
        int bCifra = b % 10;
        int kCifra = k % 10;
        int result = abs(aCifra - bCifra);
        if (result < kCifra) {
            komb = aCifra * stepen;
        } else if (result > kCifra) {
            komb = bCifra * stepen;
        }

        if (result != kCifra) {
            stepen *= 10;;
        }
        a = a / 10;
        b = b / 10;
        k = k / 10;
    }
    return komb;
}

int main() {
    int a, b, k;
    while (cin >> a >> b >> k) {
        int kombiniran = transform(a, b, k);
        cout << kombiniran << endl;
    }
}
